/** The deepest an include nests: one past it renders nothing. */
export const INCLUDE_DEPTH = 8;

/** A template that does not parse: its name and why. */
export class TemplateError extends Error {}

/** Whether `text` is a path (names joined by dots), split at its dots. */
function pathOf(name, text) {
  if (text === '') throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
  const parts = text.split('.');
  for (const p of parts) {
    if (p === '') throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
    const c0 = p.charCodeAt(0);
    if (!((c0 >= 65 && c0 <= 90) || (c0 >= 97 && c0 <= 122) || c0 === 95))
      throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
    for (let i = 1; i < p.length; i++) {
      const c = p.charCodeAt(i);
      if (!((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95))
        throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
    }
  }
  return parts;
}

/** Whether `src` holds only spaces/tabs between `a` and `b`. */
function onlySpacesTabs(src, a, b) {
  for (let i = a; i < b; i++) {
    const c = src.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** `src`'s tokens: text, {{ }}, {{{ }}} and {% %}, a standalone tag's line taken with it. */
function tokenize(name, src) {
  const tokens = [];
  let text = '';
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open === -1 || open === src.length - 1) {
      text += src.slice(i);
      break;
    }
    const next = src[open + 1];
    if (next !== '{' && next !== '%') {
      text += src.slice(i, open + 1);
      i = open + 1;
      continue;
    }
    text += src.slice(i, open);
    if (next === '{') {
      const raw = src[open + 2] === '{';
      const close = src.indexOf(raw ? '}}}' : '}}', open + (raw ? 3 : 2));
      if (close === -1) throw new TemplateError(`template "${name}": a ${raw ? '{{{' : '{{'} is not closed`);
      if (text !== '') tokens.push({ t: 'text', text });
      text = '';
      tokens.push({ t: raw ? 'raw' : 'var', path: pathOf(name, src.slice(open + (raw ? 3 : 2), close).trim()) });
      i = close + (raw ? 3 : 2);
      continue;
    }
    const close = src.indexOf('%}', open + 2);
    if (close === -1) throw new TemplateError(`template "${name}": a {% is not closed`);
    const end = close + 2;
    const lineStart = src.lastIndexOf('\n', open - 1) + 1;
    const nl = src.indexOf('\n', end);
    const lineEnd = nl === -1 ? src.length : nl;
    const standalone = onlySpacesTabs(src, lineStart, open) && onlySpacesTabs(src, end, lineEnd);
    if (standalone) text = text.slice(0, text.length - (open - lineStart));
    if (text !== '') tokens.push({ t: 'text', text });
    text = '';
    tokens.push({ t: 'tag', tag: src.slice(open + 2, close).trim() });
    i = standalone ? (nl === -1 ? src.length : nl + 1) : end;
  }
  if (text !== '') tokens.push({ t: 'text', text });
  return tokens;
}

/** A name of [A-Za-z_][A-Za-z0-9_]*, or -1. */
function scanName(s, from) {
  if (from >= s.length) return -1;
  const c0 = s.charCodeAt(from);
  if (!((c0 >= 65 && c0 <= 90) || (c0 >= 97 && c0 <= 122) || c0 === 95)) return -1;
  let i = from + 1;
  while (i < s.length) {
    const c = s.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95) i++;
    else break;
  }
  return i;
}

/** Whether `s` from `from` is non-whitespace to its end. */
function isNonSpaceToEnd(s, from) {
  if (from >= s.length) return false;
  for (let i = from; i < s.length; i++) if (isWs(s.charCodeAt(i))) return false;
  return true;
}

/** `src` parsed into its tree of nodes (a TemplateError when it does not parse). */
export function parseTemplate(name, src) {
  const root = { kind: 'root', body: [] };
  const stack = [root];
  let body = root.body;
  for (const tok of tokenize(name, src)) {
    if (tok.t === 'text') body.push({ kind: 'text', text: tok.text });
    else if (tok.t === 'var' || tok.t === 'raw') body.push({ kind: tok.t, path: tok.path });
    else {
      const tag = tok.tag;
      const top = stack[stack.length - 1];
      let m;
      // {% for x in path %}
      if (tag.startsWith('for ')) {
        const nameEnd = scanName(tag, 4);
        if (nameEnd !== -1 && tag.startsWith(' in ', nameEnd) && isNonSpaceToEnd(tag, nameEnd + 4)) {
          const node = { kind: 'for', name: tag.slice(4, nameEnd), path: pathOf(name, tag.slice(nameEnd + 4)), body: [] };
          body.push(node);
          stack.push(node);
          body = node.body;
          continue;
        }
      }
      // {% if path %} / {% if not path %}
      if (tag.startsWith('if ')) {
        let p = 3;
        let not = false;
        if (tag.startsWith('not ', 3)) {
          not = true;
          p = 7;
        }
        if (isNonSpaceToEnd(tag, p)) {
          const node = { kind: 'if', not, path: pathOf(name, tag.slice(p)), then: [], else: null };
          body.push(node);
          stack.push(node);
          body = node.then;
          continue;
        }
      }
      if (tag === 'else') {
        if (top.kind !== 'if' || top.else !== null) throw new TemplateError(`template "${name}": an else outside an if`);
        top.else = [];
        body = top.else;
      } else if (tag === 'endfor' || tag === 'endif') {
        if (top.kind !== (tag === 'endfor' ? 'for' : 'if')) throw new TemplateError(`template "${name}": an ${tag} with no open ${tag.slice(3)}`);
        stack.pop();
        const parent = stack[stack.length - 1];
        body = parent.kind === 'root' ? parent.body : parent.kind === 'for' ? parent.body : parent.else ?? parent.then;
      } else if (tag.startsWith('include "') && tag.endsWith('"') && tag.length > 10) {
        const inner = tag.slice(9, -1);
        let ok = inner.length > 0;
        for (let i = 0; ok && i < inner.length; i++) {
          const c = inner.charCodeAt(i);
          if (!((c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 45)) ok = false;
        }
        if (ok) {
          body.push({ kind: 'include', name: inner });
          continue;
        }
        throw new TemplateError(`template "${name}": {% ${tag} %} is not a tag`);
      } else throw new TemplateError(`template "${name}": {% ${tag} %} is not a tag`);
    }
  }
  if (stack.length > 1) throw new TemplateError(`template "${name}": a ${stack[stack.length - 1].kind} is not closed`);
  return root.body;
}

/** The value at `path` in the flat scope `vars`: its first name there, then own properties. */
function lookup(vars, path) {
  if (!Object.hasOwn(vars, path[0])) return undefined;
  let v = vars[path[0]];
  for (let k = 1; k < path.length; k++) {
    if (v === null || typeof v !== 'object' || !Object.hasOwn(v, path[k])) return undefined;
    v = v[path[k]];
  }
  return v;
}

/** A value as text: a string itself, a number in JavaScript's digits, true or false, an array's items joined by ", ", else "". */
function textOf(v) {
  if (typeof v === 'string') return v;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.map(textOf).join(', ');
  return '';
}

/** Whether a value counts as true in an if: not undefined, null, false, "", 0 or an empty array. */
function truthy(v) {
  if (Array.isArray(v)) return v.length > 0;
  return v !== undefined && v !== null && v !== false && v !== '' && v !== 0;
}

/**
 * `nodes` rendered in `vars` (one flat scope object) into `out`. `ctx` holds
 * the parsed templates, the HTML escape and the include depth.
 *
 * A for loop binds its element and `loop` in the same flat object, saving
 * and restoring whatever was there before, which is exactly the reference's
 * innermost-scope-wins rule without a scope chain or a fresh object per
 * iteration. (`loop` is set after the element, so it wins when both share a
 * name, as in the reference's `{ [name]: x, loop: ... }`.)
 */
export function renderNodes(nodes, vars, ctx, depth, out) {
  for (const n of nodes) {
    switch (n.kind) {
      case 'text':
        out.push(n.text);
        break;
      case 'var':
        out.push(ctx.escape(textOf(lookup(vars, n.path))));
        break;
      case 'raw':
        out.push(textOf(lookup(vars, n.path)));
        break;
      case 'if': {
        const v = truthy(lookup(vars, n.path));
        const branch = v !== n.not ? n.then : n.else;
        if (branch !== null) renderNodes(branch, vars, ctx, depth, out);
        break;
      }
      case 'for': {
        const xs = lookup(vars, n.path);
        if (!Array.isArray(xs)) break;
        const hadName = Object.hasOwn(vars, n.name);
        const prevName = vars[n.name];
        const hadLoop = Object.hasOwn(vars, 'loop');
        const prevLoop = vars.loop;
        const loop = { index: 0, first: false, last: false, length: xs.length };
        for (let k = 0; k < xs.length; k++) {
          vars[n.name] = xs[k];
          vars.loop = loop;
          loop.index = k + 1;
          loop.first = k === 0;
          loop.last = k === xs.length - 1;
          renderNodes(n.body, vars, ctx, depth, out);
        }
        if (hadName) vars[n.name] = prevName;
        else delete vars[n.name];
        if (hadLoop) vars.loop = prevLoop;
        else delete vars.loop;
        break;
      }
      case 'include': {
        const t = ctx.templates.get(n.name);
        if (t !== undefined && depth < INCLUDE_DEPTH) renderNodes(t, vars, ctx, depth + 1, out);
        break;
      }
    }
  }
}

